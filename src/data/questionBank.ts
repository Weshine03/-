/**
 * 依序挑選五感任務（固定五感依序闖關：視覺 -> 聽覺 -> 嗅覺 -> 味覺 -> 觸覺）
 */
export function generateRoundMissions(
  usedQuestionIds: string[] = [],
  _roundNumber: number = 1
): { missions: Mission[]; isBankExhausted: boolean } {
  const canonicalSenses: SensoryType[] = ['visual', 'auditory', 'olfactory', 'gustatory', 'tactile'];

  const availableBySense = {
    visual: QUESTION_BANK.filter((q) => q.sensoryType === 'visual' && !usedQuestionIds.includes(q.id)),
    auditory: QUESTION_BANK.filter((q) => q.sensoryType === 'auditory' && !usedQuestionIds.includes(q.id)),
    olfactory: QUESTION_BANK.filter((q) => q.sensoryType === 'olfactory' && !usedQuestionIds.includes(q.id)),
    gustatory: QUESTION_BANK.filter((q) => q.sensoryType === 'gustatory' && !usedQuestionIds.includes(q.id)),
    tactile: QUESTION_BANK.filter((q) => q.sensoryType === 'tactile' && !usedQuestionIds.includes(q.id)),
  };

  const isBankExhausted = canonicalSenses.some((s) => availableBySense[s].length === 0);
  if (isBankExhausted) {
    return {
      missions: [],
      isBankExhausted: true,
    };
  }

  // Pick the first unused question for each sense in strictly canonical order
  const finalMissions: Mission[] = canonicalSenses.map((s, idx) => {
    const list = availableBySense[s];
    const picked = list[0];
    return {
      ...picked,
      subtitle: `第 ${idx + 1} 個海域：${getSensoryStageName(picked.sensoryType)} · ${picked.title}`,
    };
  });

  return {
    missions: finalMissions,
    isBankExhausted: false,
  };
}

function getSensoryStageName(type: SensoryType): string {
  switch (type) {
    case 'visual': return '視覺觀察';
    case 'auditory': return '聽覺觀察';
    case 'olfactory': return '嗅覺觀察';
    case 'gustatory': return '味覺觀察';
    case 'tactile': return '觸覺觀察';
    default: return '感官觀察';
  }
}
